def stimulus(rng, cycles):
    seq = []
    def add(reset, data):
        seq.append({'reset': reset, 'data': data})
    add(1, 0)
    add(1, 1)
    add(0, 1)
    add(0, 1)
    add(0, 0)
    add(0, 1)
    add(0, 1)
    add(0, 1)
    add(0, 0)
    add(0, 1)
    add(0, 0)
    add(0, 1)
    add(0, 1)
    add(0, 0)
    add(0, 1)
    add(1, 0)
    add(0, 1)
    add(0, 1)
    add(0, 0)
    add(0, 1)
    add(0, 1)
    add(0, 1)
    add(0, 0)
    add(0, 1)
    add(0, 0)
    add(0, 1)
    add(0, 1)
    add(0, 0)
    add(0, 1)
    add(1, 1)
    add(0, 1)
    add(0, 1)
    add(0, 0)
    add(0, 1)
    add(0, 1)
    add(0, 1)
    add(0, 0)
    add(0, 1)
    add(0, 0)
    add(0, 1)
    add(0, 1)
    add(0, 0)
    add(0, 1)
    while len(seq) < cycles:
        r = rng.random()
        if r < 0.05:
            add(1, rng.getrandbits(1))
        elif r < 0.15:
            add(0, 1)
        elif r < 0.25:
            add(0, 0)
        else:
            add(0, rng.getrandbits(1))
    return seq[:cycles]
